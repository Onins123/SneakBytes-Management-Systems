    private void loadTableData(){
        try{
            String filePath = "src/main/java/sneakbytes/logs.txt";
            File file = new File(filePath);
            Scanner scan = new Scanner(file);
            DefaultTableModel tM = (DefaultTableModel)jTable1.getModel();
            
            while(scan.hasNext()){
                String input = scan.nextLine();
                String separate[] = input.split(" ");
                String toInput[] = {separate[0], separate[1], separate[2], separate[3], separate[4], separate[5], separate[6]};
                tM.addRow(toInput);
                
                
            }      
        } catch (IOException e) {
            Logger.getLogger(Inventory.class.getName()).log(Level.SEVERE, null, e);
        }
    }
    
    
    
    
    
    

