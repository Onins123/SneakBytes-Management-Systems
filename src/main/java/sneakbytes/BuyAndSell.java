    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed

        // set text to total
        String Total = "";
        if(price.getText().equals("") || quantity.getText().equals("")){
            JOptionPane.showMessageDialog(this, "Please fill price and quantity data!");
        }else{
            int prc = Integer.parseInt(price.getText());
            int qnty = Integer.parseInt(quantity.getText());
            Total = Integer.toString(prc * qnty);
        }
        // check if text fields are empty
        if(item.getText().equals("")||price.getText().equals("")||size.getText().equals("")||color.getText().equals("")||quantity.getText().equals("")){
            JOptionPane.showMessageDialog(this, "Please fill all data!");
        }else if(Integer.parseInt(quantity.getText()) > 0){
            //strong all value to a string array
            String data[] = {item.getText(),size.getText(),color.getText(),quantity.getText(),price.getText(), Total};
            //instantiate the table
            DefaultTableModel tM = (DefaultTableModel) table.getModel();
            //add the array values to the table
            tM.addRow(data);
            //clear the text fields
            item.setText("");
            price.setText("");
            size.setText("");
            color.setText("");
            quantity.setText("");
        }else if(Integer.parseInt(quantity.getText()) <= 0){
        JOptionPane.showMessageDialog(this, "Invalid quantity input!");
        }

    }//GEN-LAST:event_addButtonActionPerformed

