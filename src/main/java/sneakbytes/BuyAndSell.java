    private void sellButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_sellButtonActionPerformed
        //instantiate the table
        DefaultTableModel tM = (DefaultTableModel) table.getModel();
         String logPath = "src/main/java/sneakbytes/logs.txt";
         String filePath = "src/main/java/sneakbytes/buy.txt";
        File file = new File(filePath);
        File logFile = new File(logPath);
        try {
            try (FileWriter fw = new FileWriter(file, true); 
                    BufferedWriter bf = new BufferedWriter(fw)) {
                
                for(int i = 0; i < tM.getRowCount(); i++){
                    for(int j = 0; j < tM.getColumnCount() - 1; j++){
                        if(j == 3){
                        bf.write("-" + tM.getValueAt(i, j).toString() + " ");
                        }
                        else{
                            bf.write(tM.getValueAt(i, j).toString() + " ");
                        }
                    }
                    bf.write("\n");
                }

                bf.close();
                fw.close();
            }
        } catch (IOException ex) {
            Logger.getLogger(BuyAndSell.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        try {
               FileWriter lw = new FileWriter(logFile, true);
            try (BufferedWriter bw = new BufferedWriter(lw)) {
                for(int i = 0; i < tM.getRowCount(); i++){
                 bw.write("Sell ");   
                    for(int j = 0; j < tM.getColumnCount() - 1; j++){
                        bw.write(tM.getValueAt(i, j).toString() + " ");
                    }
                    bw.write(LocalDate.now().toString() + " ");
                    bw.write("\n");
                }
                
                
                JOptionPane.showMessageDialog(this, "Sell transaction completed!");
                bw.close();
                lw.close();
            }
            
        } catch (IOException ex) {
            Logger.getLogger(BuyAndSell.class.getName()).log(Level.SEVERE, null, ex);
        }

        tM.setRowCount(0);
    }//GEN-LAST:event_sellButtonActionPerformed

